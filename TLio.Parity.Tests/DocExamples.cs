/// <summary>
/// One documented example: a document and a script, written once as JSON.
/// <c>DocExamples/{commands|functions}/&lt;Page&gt;.json</c> is an array of these.
/// </summary>
public sealed class DocExample
{
    public required string Title { get; init; }
    public string? Description { get; init; }
    public required JToken Input { get; init; }
    public required JArray Script { get; init; }

    /// <summary>Set when the formats legitimately differ; shown on the page instead of asserted.</summary>
    public string? Diverges { get; init; }

    /// <summary>Hand-written XML script, for the commands whose paths XPath cannot be derived from the JSON ones.</summary>
    public string? XmlScript { get; init; }

    /// <summary>Hand-written XML document, for inputs that hold a path or text written in one format's own language.</summary>
    public string? XmlInput { get; init; }

    /// <summary>
    /// For <c>convert</c>, which changes the document's format and so cannot run on one engine:
    /// the format each tab converts to, keyed by the format it starts in. The script's
    /// <c>{to}</c> is filled in per tab, and the run goes through <see cref="MultiFormatScriptRunner"/>.
    /// </summary>
    public JObject? ConvertTo { get; init; }

    /// <summary>Where a starting format's result is not <see cref="Expected"/>: XML's document element becomes a JSON key.</summary>
    public JObject? ExpectedByStart { get; init; }

    /// <summary>The result the example must produce; for a fixture-backed example, the fixture's own.</summary>
    public required JToken Expected { get; init; }

    /// <summary>Repo-relative test fixture this example is read from, or null for a hand-written one.</summary>
    public string? Source { get; init; }

    public DocExample With(string diverges) => new()
    {
        Title = Title, Description = Description, Input = Input, Script = Script,
        Diverges = diverges, XmlScript = XmlScript, XmlInput = XmlInput, ConvertTo = ConvertTo, ExpectedByStart = ExpectedByStart, Expected = Expected, Source = Source
    };
}

/// <summary>What one example looks like, and what it produced, in each format's own words.</summary>
public sealed record FormatRun(string Language, string Input, string Script, string Result, string Normalised, string? Error, string? ResultLanguage = null);

/// <summary>
/// Turns the example corpus into the "Examples in every format" section of each reference page.
///
/// <para>Nothing on the page is typed by hand: the script is written out in each notation, the
/// engine runs <i>that text</i> against <i>that document</i>, and the result shown is what came
/// back. A page therefore cannot show an outcome the engine does not produce, and
/// <see cref="DocsAreUpToDate"/> fails when a page and the engine drift apart.</para>
///
/// <para>Regenerate after changing an example or behaviour:
/// <c>dotnet test TLio.Parity.Tests --filter "Name~GenerateDocExamples"</c>.</para>
/// </summary>
[TestFixture]
public sealed class DocExamples
{
    private const string Begin = "<!-- formats:begin — generated by TLio.Parity.Tests (DocExamples); edit DocExamples/*.json, not this block -->";
    private const string End = "<!-- formats:end -->";

    private static readonly string[] Kinds = { "commands", "functions" };

    // ── Tests ─────────────────────────────────────────────────────────────────

    [Test]
    public void DocsAreUpToDate()
    {
        var root = RepoRoot();
        Assume.That(root, Is.Not.Null, "docs/ not found next to the test output");

        var problems = new List<string>();
        foreach (var (kind, name, examples) in Corpus())
        {
            var page = PagePath(root!, kind, name);
            if (!File.Exists(page)) { problems.Add($"{kind}/{name}: no page {page}"); continue; }

            var (block, errors) = Render(examples);
            problems.AddRange(errors.Select(e => $"{kind}/{name}: {e}"));

            if (Splice(File.ReadAllText(page), block) != File.ReadAllText(page).Replace("\r\n", "\n"))
                problems.Add($"{kind}/{name}: page is stale — run the GenerateDocExamples test");
        }

        Assert.That(problems, Is.Empty, string.Join("\n", problems));
    }

    [Test, Explicit("Rewrites docs/ai-ref pages")]
    public void GenerateDocExamples()
    {
        var root = RepoRoot() ?? throw new InvalidOperationException("repository root not found");
        var problems = new List<string>();

        foreach (var (kind, name, examples) in Corpus())
        {
            var page = PagePath(root, kind, name);
            var (block, errors) = Render(examples);
            problems.AddRange(errors.Select(e => $"{kind}/{name}: {e}"));
            File.WriteAllText(page, Splice(File.ReadAllText(page), block));
        }

        Assert.That(problems, Is.Empty, string.Join("\n", problems));
    }

    [Test]
    public void EveryPageHasExamples()
    {
        var root = RepoRoot();
        Assume.That(root, Is.Not.Null);

        var exempt = new HashSet<string>();
        var have = Corpus().Select(c => $"{c.Kind}/{c.Name}").ToHashSet();
        var missing = Kinds
            .SelectMany(k => Directory.GetFiles(Path.Combine(root!, "docs", "ai-ref", k), "*.md")
                .Select(f => $"{k}/{Path.GetFileNameWithoutExtension(f)}"))
            .Where(p => !have.Contains(p) && !exempt.Contains(p))
            .OrderBy(p => p).ToList();

        Assert.That(missing, Is.Empty, "pages with no cross-format example:\n" + string.Join("\n", missing));
    }

    [Test]
    public void IndexLinksEveryPageAndEveryLinkResolves()
    {
        var root = RepoRoot();
        Assume.That(root, Is.Not.Null);

        var problems = new List<string>();
        var index = Path.Combine(root!, "docs", "ai-ref", "README.md");

        // Every link in the two entry points must point at a file that exists.
        var documents = new List<string> { index, Path.Combine(root!, "README.md"), Path.Combine(root!, "CONTRIBUTING.md") };
        documents.AddRange(Directory.GetFiles(Path.Combine(root!, "docs", "release-notes"), "*.md"));

        foreach (var doc in documents)
        {
            var text = File.ReadAllText(doc);
            foreach (Match m in Regex.Matches(text, @"\]\(([^)\s#]+)(#[^)]*)?\)"))
            {
                var target = m.Groups[1].Value;
                if (target.Contains("://") || target.StartsWith("mailto:")) continue;
                var full = Path.GetFullPath(Path.Combine(Path.GetDirectoryName(doc)!, target));
                if (!File.Exists(full) && !Directory.Exists(full))
                    problems.Add($"{Path.GetRelativePath(root!, doc)}: broken link {target}");
            }
        }

        // And the index must reach every command and function page.
        var indexText = File.ReadAllText(index);
        foreach (var kind in Kinds)
            foreach (var page in Directory.GetFiles(Path.Combine(root!, "docs", "ai-ref", kind), "*.md"))
                if (!indexText.Contains($"]({kind}/{Path.GetFileName(page)})"))
                    problems.Add($"docs/ai-ref/README.md does not link {kind}/{Path.GetFileName(page)}");

        Assert.That(problems, Is.Empty, string.Join("\n", problems));
    }

    // ── Corpus ────────────────────────────────────────────────────────────────

    private static IEnumerable<(string Kind, string Name, List<DocExample> Examples)> Corpus()
    {
        foreach (var kind in Kinds)
        {
            var dir = Path.Combine(TestContext.CurrentContext.TestDirectory, "DocExamples", kind);
            if (!Directory.Exists(dir)) continue;

            foreach (var file in Directory.GetFiles(dir, "*.json").OrderBy(f => f, StringComparer.Ordinal))
            {
                JArray array;
                using (var reader = new JsonTextReader(new StringReader(File.ReadAllText(file)))
                       { DateParseHandling = DateParseHandling.None })
                    array = JArray.Load(reader);

                var examples = array.Cast<JObject>().Select(Load).ToList();

                yield return (kind, Path.GetFileNameWithoutExtension(file), examples);
            }
        }
    }

    /// <summary>
    /// An example is either read straight from an existing test fixture (<c>source</c>) - so the
    /// page shows the very case that test asserts - or written out with its <c>expected</c> result.
    /// Both are checked against the engine; neither is merely recorded.
    /// </summary>
    private static DocExample Load(JObject o)
    {
        var source = o["source"]?.ToString();
        JObject body = o;
        if (source is not null)
        {
            var root = RepoRoot() ?? throw new InvalidOperationException("repository root not found");
            using var reader = new JsonTextReader(new StringReader(File.ReadAllText(Path.Combine(root, source))))
                { DateParseHandling = DateParseHandling.None };
            body = JObject.Load(reader);
        }

        return new DocExample
        {
            Title       = Humanise(o["title"]!.ToString()),
            Description = o["description"]?.ToString(),
            Input       = body["input"]!,
            Script      = (JArray)body["script"]!,
            Expected    = body["result"] ?? body["expected"] ?? throw new InvalidOperationException($"no expected result for '{o["title"]}'"),
            Diverges    = o["diverges"]?.ToString(),
            XmlScript   = o["xmlScript"]?.ToString(),
            XmlInput    = o["xmlInput"]?.ToString(),
            ConvertTo   = o["convertTo"] as JObject,
            ExpectedByStart = o["expectedByStart"] as JObject,
            Source      = source
        };
    }

    /// <summary>A rendered document with the platform's line ending (JSON-escaped) read as LF.</summary>
    private static string Lf(string rendered) => rendered.Replace("\\r\\n", "\\n");

    private static string Humanise(string title) =>
        Regex.IsMatch(title, @"^\d+-") ? Regex.Replace(title, @"^\d+-", "").Replace('-', ' ') : title;

    private static string? RepoRoot()
    {
        var dir = new DirectoryInfo(TestContext.CurrentContext.TestDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "TLio.sln"))) dir = dir.Parent;
        return dir?.FullName;
    }

    private static string PagePath(string root, string kind, string name) =>
        Path.Combine(root, "docs", "ai-ref", kind, name + ".md");

    // ── Page section ──────────────────────────────────────────────────────────

    private static string Splice(string page, string block)
    {
        page = page.Replace("\r\n", "\n");
        var section = $"{Begin}\n{block}{End}\n";

        var start = page.IndexOf(Begin, StringComparison.Ordinal);
        if (start >= 0)
        {
            var end = page.IndexOf(End, start, StringComparison.Ordinal) + End.Length;
            return page[..start] + section.TrimEnd('\n') + page[end..];
        }

        // New section: before "When to use" so the reader meets the examples before the advice.
        var anchor = page.IndexOf("\n## When to use", StringComparison.Ordinal);
        return anchor >= 0
            ? page[..(anchor + 1)] + section + "\n" + page[(anchor + 1)..]
            : page.TrimEnd('\n') + "\n\n" + section;
    }

    private static (string Block, List<string> Errors) Render(List<DocExample> examples)
    {
        var errors = new List<string>();
        var sb = new StringBuilder();
        sb.Append("## Examples in every format\n\n");
        sb.Append("Each example is run through the engine in all three formats; the result shown is what came back. Expand a format to see it.\n\n");

        foreach (var source in examples)
        {
            var ex = source;
            var converts = ex.ConvertTo is not null;
            var runs = converts
                ? new[] { RunConvert(ex, "json"), RunConvert(ex, "xml"), RunConvert(ex, "yaml") }
                : new[] { RunJson(ex), RunXml(ex), RunYaml(ex) };

            foreach (var r in runs.Where(r => r.Error is not null))
                errors.Add($"'{ex.Title}' {r.Language}: {r.Error}");

            // A conversion keeps the data, so every tab must come out as the expected document;
            // otherwise the JSON run is the reference and the other two are compared to it.
            foreach (var r in converts ? runs : runs.Take(1))
            {
                var start = r.Language.Split(' ')[0].ToLowerInvariant();
                var want = FormatRunners.RenderForComparison(ex.ExpectedByStart?[start] ?? ex.Expected);
                if (r.Error is null && Lf(r.Normalised) != want)
                    errors.Add($"'{ex.Title}' {r.Language} - result does not match the expected result:\n    expected: {want}\n    actual:   {Lf(r.Normalised)}");
            }

            var differ = !converts && runs.All(r => r.Error is null) && runs.Select(r => Lf(r.Normalised)).Distinct().Count() > 1;
            if (differ)
            {
                TestContext.Out.WriteLine($"DIFFERS '{ex.Title}':\n" + string.Join("\n", runs.Select(r => $"    {r.Language}: {r.Normalised}")));
                if (ex.Diverges is null)
                    ex = ex.With("the results below are not identical — a path, an embedded text or a number is spelled in each format's own way. Compare the three.");
            }

            sb.Append($"**{ex.Title}**\n\n");
            if (ex.Description is not null) sb.Append(ex.Description).Append("\n\n");
            if (ex.Source is not null) sb.Append($"<sub>Test: `{ex.Source}`</sub>\n\n");
            if (ex.Diverges is not null) sb.Append($"> **Differs by format:** {ex.Diverges}\n\n");

            foreach (var r in runs)
            {
                var lang = r.Language;
                var fence = lang.Split(' ')[0].ToLowerInvariant();
                var resultFence = (r.ResultLanguage ?? lang).Split(' ')[0].ToLowerInvariant();
                sb.Append($"<details>\n<summary>{lang}</summary>\n\n");
                sb.Append($"Input\n\n```{fence}\n{r.Input.TrimEnd()}\n```\n\n");
                sb.Append($"Script\n\n```{fence}\n{r.Script.TrimEnd()}\n```\n\n");
                sb.Append($"Result\n\n```{resultFence}\n{r.Result.TrimEnd()}\n```\n\n");
                sb.Append("</details>\n\n");
            }
        }

        // XElement.ToString() and toCsv use the platform newline; a page is always LF.
        return (Lf(sb.ToString().Replace("\r\n", "\n")), errors);
    }

    // ── Runs: the displayed text is the text that is executed ────────────────

    /// <summary>The sweep's command set plus convertValue/convert, which the sweep must not see.</summary>
    private static ParseOptions<TNode> Options<TNode>(string documentFormat)
    {
        var converter = new TLio.FormatConverter.Core.FormatConverter();
        converter.Register(new TLio.FormatConverter.Json.JsonFormatAdapter());
        converter.Register(new TLio.FormatConverter.Xml.XmlFormatAdapter());
        converter.Register(new TLio.FormatConverter.Yaml.YamlFormatAdapter());

        var options = FormatRunners.Options<TNode>();
        options.CommandsProvider.RegisterFormatConversion<TNode>(converter, documentFormat);
        return options;
    }

    private static FormatRun RunConvert(DocExample ex, string start)
    {
        var target = ex.ConvertTo![start]!.ToString();
        var label = $"{start.ToUpperInvariant()} → {target.ToUpperInvariant()}";

        var scriptJson = ex.Script.ToString(Formatting.None).Replace("{to}", target);
        var (input, script) = start switch
        {
            "xml"  => (XElement.Parse(CanonicalShape.ToXmlDocument(ex.Input)).ToString(),
                       XElement.Parse(CanonicalShape.ToXmlScript(scriptJson)).ToString()),
            "yaml" => (CanonicalShape.ToYamlDocument(ex.Input), CanonicalShape.ToYamlDocument(JArray.Parse(scriptJson))),
            _      => (ex.Input.ToString(Formatting.Indented), JArray.Parse(scriptJson).ToString(Formatting.Indented))
        };

        try
        {
            var converter = new TLio.FormatConverter.Core.FormatConverter();
            converter.Register(new TLio.FormatConverter.Json.JsonFormatAdapter());
            converter.Register(new TLio.FormatConverter.Xml.XmlFormatAdapter());
            converter.Register(new TLio.FormatConverter.Yaml.YamlFormatAdapter());

            var runner = new MultiFormatScriptRunner(converter);
            runner.RegisterExecutor(Section<JToken>("json", JsonExecutionContext.CreateDefault));
            runner.RegisterExecutor(Section<XElement>("xml", XmlExecutionContext.CreateWithNativeXPath));
            runner.RegisterExecutor(Section<YamlNode>("yaml", YamlExecutionContext.CreateDefault));

            var result = runner.Run(start, input, script);
            if (!result.Success)
                return new FormatRun(label, input, script, "", "", string.Join("; ", result.Logs.Select(l => l.Message)));

            var normalised = result.FormatId switch
            {
                "xml"  => FormatRunners.RenderXmlForComparison(new XmlNodeAdapter().Parse(result.Document)),
                "yaml" => FormatRunners.RenderYamlForComparison(YamlExecutionContext.CreateDefault().NodeAdapter.Parse(result.Document)),
                _      => FormatRunners.RenderForComparison(ParseJson(result.Document))
            };
            var shown = result.FormatId == "json" ? ParseJson(result.Document).ToString(Formatting.Indented)
                      : result.FormatId == "xml" ? XElement.Parse(result.Document).ToString()
                      : result.Document;
            return new FormatRun(label, input, script, shown, normalised, null, target);
        }
        catch (Exception e) { return new FormatRun(label, input, script, "", "", e.Message); }
    }

    private static ScriptEngineSectionExecutor<TNode> Section<TNode>(
        string formatId, Func<TLio.Core.Models.ExecutionContext<TNode>> contextFactory)
    {
        var options = ParseOptions<TNode>.CreateDefault();
        var engine = new ScriptEngine<TNode>(options.CommandsProvider, options.FunctionsProvider);
        return new ScriptEngineSectionExecutor<TNode>(formatId, engine, () => contextFactory());
    }

    private static FormatRun RunJson(DocExample ex)
    {
        var input  = ex.Input.ToString(Formatting.Indented);
        var script = ex.Script.ToString(Formatting.Indented);
        try
        {
            var options = Options<JToken>("json");
            var engine  = new ScriptEngine<JToken>(options.CommandsProvider, options.FunctionsProvider);
            var data    = ParseJson(input);
            var result  = engine.Execute(script, data, JsonExecutionContext.CreateDefault());
            return new FormatRun("JSON", input, script, result.Data.ToString(Formatting.Indented),
                FormatRunners.RenderForComparison(result.Data), null);
        }
        catch (Exception e) { return new FormatRun("JSON", input, script, "", "", e.Message); }
    }

    private static JToken ParseJson(string text)
    {
        using var reader = new JsonTextReader(new StringReader(text)) { DateParseHandling = DateParseHandling.None };
        return JToken.Load(reader);
    }

    private static FormatRun RunXml(DocExample ex)
    {
        var input  = XElement.Parse(ex.XmlInput ?? CanonicalShape.ToXmlDocument(ex.Input)).ToString();
        var script = XElement.Parse(ex.XmlScript ?? CanonicalShape.ToXmlScript(ex.Script.ToString(Formatting.None))).ToString();
        try
        {
            var options = Options<XElement>("xml");
            var adapter = new XmlNodeAdapter();
            var parser  = new XmlScriptParser<XElement>(options.CommandsProvider, options.FunctionsProvider, adapter);
            var context = XmlExecutionContext.CreateWithSlashPaths();
            var result  = parser.ParseScript(script).Execute(adapter.Parse(input), context);
            foreach (var l in context.GetLogEntries().Where(l => l.Level.ToString() == "Warning")) TestContext.Out.WriteLine($"LOG {ex.Title} XML [{l.Level}] {l.Message}");
            return new FormatRun("XML", input, script, result.Data.ToString(),
                FormatRunners.RenderXmlForComparison(result.Data), null);
        }
        catch (Exception e) { return new FormatRun("XML", input, script, "", "", e.Message); }
    }

    private static FormatRun RunYaml(DocExample ex)
    {
        var input  = CanonicalShape.ToYamlDocument(ex.Input);
        var script = CanonicalShape.ToYamlDocument(ex.Script);
        try
        {
            var options = Options<YamlNode>("yaml");
            var context = YamlExecutionContext.CreateDefault();
            var adapter = context.NodeAdapter;
            var parser  = new YamlScriptParser<YamlNode>(options.CommandsProvider, options.FunctionsProvider, adapter);
            var result  = parser.ParseScript(script).Execute(adapter.Parse(input), context);
            return new FormatRun("YAML", input, script, adapter.Serialize(result.Data, true),
                FormatRunners.RenderYamlForComparison(result.Data), null);
        }
        catch (Exception e) { return new FormatRun("YAML", input, script, "", "", e.Message); }
    }
}
